import { expect, test } from '@playwright/test';
import { readFile, savedDiagram } from './storage';

test('cloud boundaries are real groups and the custom table editor fits a phone', async ({ page }) => {
  await page.goto('/app/');
  await page.getByRole('button', {name:'Biblioteca de componentes',exact:true}).click();
  let library = page.getByRole('dialog', {name:'Biblioteca de componentes'});
  await library.getByRole('textbox', {name:'Buscar componente'}).fill('Virtual private cloud VPC');
  await library.getByRole('button', {name:'Adicionar Virtual private cloud VPC',exact:true}).click();
  await page.locator('.strukt-label-input').press('Enter');
  await expect.poll(async () => (await savedDiagram(page))?.model.elements['Virtual private cloud VPC']?.kind).toBe('group');
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button', {name:/^Mostrar\/ocultar barra lateral/}).click();
  await page.getByRole('button', {name:'Biblioteca de componentes',exact:true}).click();
  library = page.getByRole('dialog', {name:'Biblioteca de componentes'});
  await library.getByRole('button', {name:'Criar componente',exact:true}).click();
  const editor = page.getByRole('dialog', {name:'Criar componente próprio'});
  await editor.getByRole('textbox', {name:'Nome do componente'}).fill('Tabela mobile');
  await editor.getByRole('combobox', {name:'Apresentação',exact:true}).selectOption('table');
  await editor.getByRole('textbox', {name:'Tipo do campo 1'}).fill('uuid');
  const overflow = await editor.evaluate(element => element.scrollWidth > element.clientWidth);
  expect(overflow).toBe(false);
  const field = await editor.getByRole('textbox', {name:'Tipo do campo 1'}).boundingBox();
  expect(field!.x + field!.width).toBeLessThanOrEqual(390);
  await editor.getByRole('button', {name:'Salvar componente',exact:true}).click();
  await expect.poll(async () => (await readFile(page,'library.json'))?.includes('Tabela mobile')).toBe(true);
});

test('official cloud icons and reusable components remain editable after reopening', async ({ page }) => {
  await page.goto('/app/');
  await page.getByRole('button', {name:'Biblioteca de componentes',exact:true}).click();
  let library = page.getByRole('dialog', {name:'Biblioteca de componentes'});
  await library.getByRole('combobox', {name:'Categoria de componentes'}).selectOption('AWS');
  await library.getByRole('textbox', {name:'Buscar componente'}).fill('AWS Lambda');
  await library.getByRole('button', {name:'Adicionar AWS Lambda',exact:true}).click();
  await page.locator('.strukt-label-input').press('Enter');
  await expect.poll(async () => (await savedDiagram(page))?.model.elements['AWS Lambda']?.icon).toBe('aws:lambda');
  await expect(page.locator('[data-id="AWS Lambda"] svg')).not.toHaveCount(0);
  await page.getByRole('button', {name:'Biblioteca de componentes',exact:true}).click();
  await library.getByRole('button', {name:'Criar componente',exact:true}).click();
  const editor = page.getByRole('dialog', {name:'Criar componente próprio'});
  await editor.getByRole('textbox', {name:'Nome do componente'}).fill('Tabela do projeto');
  await editor.getByRole('combobox', {name:'Apresentação',exact:true}).selectOption('table');
  await editor.getByRole('textbox', {name:'Tipo do campo 1'}).fill('uuid');
  await editor.getByRole('button', {name:'Ícone: server',exact:true}).click();
  const icons = page.getByRole('dialog', {name:'Escolher ícone'});
  await icons.getByRole('combobox', {name:'Buscar ícones'}).fill('database');
  await expect(icons.getByRole('combobox', {name:'Buscar ícones'})).toBeFocused();
  await icons.getByRole('option', {name:'Database (database)',exact:true}).click();
  await editor.getByRole('button', {name:'Salvar componente',exact:true}).click();
  await expect.poll(async () => (await readFile(page,'library.json'))?.includes('Tabela do projeto')).toBe(true);
  await page.getByRole('button', {name:'Biblioteca de componentes',exact:true}).click();
  library = page.getByRole('dialog', {name:'Biblioteca de componentes'});
  await library.getByRole('combobox', {name:'Categoria de componentes'}).selectOption('Meu workspace');
  await library.getByRole('button', {name:'Adicionar Tabela do projeto',exact:true}).click();
  await page.locator('.strukt-label-input').press('Enter');
  await expect(page.locator('.react-flow__node-table[data-id="Tabela do projeto"]')).toContainText('PK');
  await expect.poll(async () => (await savedDiagram(page))?.model.elements['Tabela do projeto']?.fields?.[0]?.type).toBe('uuid');
  await page.reload();
  await expect(page.locator('.react-flow__node-table[data-id="Tabela do projeto"]')).toContainText('uuid');
  await page.getByRole('button', {name:'Biblioteca de componentes',exact:true}).click();
  await library.getByRole('combobox', {name:'Categoria de componentes'}).selectOption('Meu workspace');
  await library.getByRole('button', {name:'Editar componente Tabela do projeto',exact:true}).click();
  const edit = page.getByRole('dialog', {name:'Editar componente próprio'});
  await edit.getByRole('textbox', {name:'Nome do componente'}).fill('Tabela revisada');
  await edit.getByRole('button', {name:'Salvar componente',exact:true}).click();
  await expect.poll(async () => (await readFile(page,'library.json'))?.includes('Tabela revisada')).toBe(true);
  await expect(page.locator('.react-flow__node-table[data-id="Tabela do projeto"]')).toContainText('uuid');
  await page.getByRole('button', {name:'Biblioteca de componentes',exact:true}).click();
  await library.getByRole('combobox', {name:'Categoria de componentes'}).selectOption('Meu workspace');
  await library.getByRole('button', {name:'Excluir componente Tabela revisada',exact:true}).click();
  await expect(library.getByRole('button', {name:'Adicionar Tabela revisada',exact:true})).toHaveCount(0);
  await expect.poll(() => readFile(page,'library.json')).toBeNull();
  await page.keyboard.press('Escape');
  await page.reload();
  await expect(page.locator('.react-flow__node-table[data-id="Tabela do projeto"]')).toContainText('uuid');
});

test('a workspace template saves the current positions and creates an independent new diagram', async ({ page }) => {
  await page.goto('/app/');
  await expect(page.locator('[data-id="Kafka"]')).toBeVisible();
  const original = await readFile(page,'diagrams/exemplo.strukt.json');
  await page.getByRole('button', {name:'Modelos de diagramas',exact:true}).click();
  await page.getByRole('menuitem', {name:'Salvar diagrama como template',exact:true}).click();
  const editor = page.getByRole('dialog', {name:'Salvar diagrama como template'});
  await editor.getByRole('textbox', {name:'Nome do template'}).fill('Minha arquitetura');
  await editor.getByRole('textbox', {name:'Descrição do template'}).fill('Modelo reutilizável da minha aplicação');
  await editor.getByRole('button', {name:'Salvar template',exact:true}).click();
  await expect.poll(async () => (await readFile(page,'library.json'))?.includes('Minha arquitetura')).toBe(true);
  await page.reload();
  await page.getByRole('button', {name:'Modelos de diagramas',exact:true}).click();
  await page.getByRole('menuitem', {name:'Explorar modelos',exact:true}).click();
  const gallery = page.getByRole('dialog', {name:'Modelos de diagramas'});
  await gallery.getByRole('button', {name:'Meus modelos',exact:true}).click();
  await gallery.getByRole('button', {name:'Ver modelo Minha arquitetura',exact:true}).click();
  await gallery.getByRole('button', {name:'Usar modelo',exact:true}).click();
  await expect.poll(() => readFile(page,'diagrams/minha-arquitetura.strukt.json')).not.toBeNull();
  expect(await readFile(page,'diagrams/exemplo.strukt.json')).toBe(original);
  const reused = await readFile(page,'diagrams/minha-arquitetura.strukt.json');
  expect(JSON.parse(reused!)).toEqual(JSON.parse(original!));
  await page.getByRole('button', {name:'Modelos de diagramas',exact:true}).click();
  await page.getByRole('menuitem', {name:'Explorar modelos',exact:true}).click();
  await gallery.getByRole('button', {name:'Meus modelos',exact:true}).click();
  await gallery.getByRole('button', {name:'Excluir modelo Minha arquitetura',exact:true}).click();
  await expect.poll(() => readFile(page,'library.json')).toBeNull();
  expect(await readFile(page,'diagrams/minha-arquitetura.strukt.json')).toBe(reused);
});
