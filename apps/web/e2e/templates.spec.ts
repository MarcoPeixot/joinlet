import { expect, test } from '@playwright/test';
import { TEMPLATES } from '@strukt/workspace';
import { readFile } from './storage';

test('gallery previews real templates and creates a new diagram without replacing existing content', async ({ page }) => {
  await page.goto('/app/');
  await expect(page.locator('.react-flow__node[data-id="Kafka"]')).toBeVisible();
  const original = await readFile(page, 'diagrams/exemplo.strukt.json');
  await page.getByRole('button', { name: 'Modelos de diagramas', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Explorar modelos', exact: true }).click();
  const gallery = page.getByRole('dialog', { name: 'Modelos de diagramas' });
  await expect(gallery.getByRole('button', { name: /^Ver modelo / })).toHaveCount(TEMPLATES.length);
  await expect(gallery.getByRole('img', { name: /^Prévia de / }).first()).toBeVisible();
  expect(await gallery.getByRole('img', {name: /^Prévia de /}).count()).toBeLessThan(TEMPLATES.length);
  await gallery.getByRole('button', { name: 'AWS', exact: true }).click();
  await expect(gallery.getByRole('button', { name: /^Ver modelo / })).toHaveCount(3);
  await gallery.getByRole('button', { name: 'Ver modelo Aplicação serverless na AWS', exact: true }).click();
  await expect(gallery.getByText('Será criado um novo diagrama no workspace.')).toBeVisible();
  await gallery.getByRole('button', { name: 'Usar modelo', exact: true }).click();
  await expect(gallery).toHaveCount(0);
  await expect(page.locator('.react-flow__node[data-id="Lambda"]')).toBeVisible();
  await expect.poll(() => readFile(page, 'diagrams/aplicacao-serverless-na-aws.strukt.json')).not.toBeNull();
  await expect.poll(async () => (await readFile(page, 'strukt.json'))?.includes('aplicacao-serverless-na-aws')).toBe(true);
  expect(await readFile(page, 'diagrams/exemplo.strukt.json')).toBe(original);
  await page.reload();
  await page.getByRole('navigation', { name: 'Workspace' }).getByRole('button', { name: 'Aplicação serverless na AWS', exact: true }).click();
  await expect(page.locator('.react-flow__node[data-id="Lambda"]')).toBeVisible();
});

test('an empty diagram receives table templates in one undo step', async ({ page }) => {
  await page.goto('/app/');
  await page.getByRole('button', { name: 'Mostrar/ocultar código', exact: true }).click();
  await page.locator('.cm-content').click();
  await page.keyboard.press('ControlOrMeta+a');
  await page.keyboard.insertText(JSON.stringify({ version: 1, nodes: [], connections: [] }));
  await expect(page.locator('.react-flow__node')).toHaveCount(0);
  await page.getByRole('button', { name: 'Mostrar/ocultar código', exact: true }).click();
  await page.getByRole('button', { name: 'Explorar modelos', exact: true }).click();
  const gallery = page.getByRole('dialog', { name: 'Modelos de diagramas' });
  await gallery.getByRole('textbox', { name: 'Buscar modelos' }).fill('relacional');
  await gallery.getByRole('button', { name: 'Ver modelo Banco relacional de pedidos', exact: true }).click();
  await expect(gallery.getByText('O modelo entra no diagrama vazio. Você pode desfazer.')).toBeVisible();
  await gallery.getByRole('button', { name: 'Usar modelo', exact: true }).click();
  await expect(page.locator('.react-flow__node-table')).toHaveCount(5);
  await page.keyboard.press('ControlOrMeta+z');
  await expect(page.locator('.react-flow__node')).toHaveCount(0);
  await page.keyboard.press('ControlOrMeta+Shift+z');
  await expect(page.locator('.react-flow__node-table')).toHaveCount(5);
});

test('gallery fits a phone and filters by category and search', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/app/');
  await page.getByRole('button', { name: 'Modelos de diagramas', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Explorar modelos', exact: true }).click();
  const gallery = page.getByRole('dialog', { name: 'Modelos de diagramas' });
  const box = (await gallery.boundingBox())!;
  expect(box.x).toBeGreaterThanOrEqual(0);
  expect(box.x + box.width).toBeLessThanOrEqual(390);
  await gallery.getByRole('button', { name: 'Sequência', exact: true }).click();
  await expect(gallery.getByRole('button', { name: /^Ver modelo / })).toHaveCount(1);
  await gallery.getByRole('button', { name: 'Ver modelo Requisição de API', exact: true }).click();
  await gallery.getByRole('button', { name: 'Usar modelo', exact: true }).click();
  await expect(page.locator('.react-flow__node-participant')).toHaveCount(4);
  await expect(page.locator('.react-flow__edge')).toHaveCount(6);
});

test('workspace templates persist, create independent diagrams and remain isolated from other projects', async ({ page }) => {
  await page.goto('/app/');
  await expect(page.locator('[data-id="Kafka"]')).toBeVisible();
  await page.getByRole('button', { name: 'Modelos de diagramas', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Salvar diagrama como template', exact: true }).click();
  const editor = page.getByRole('dialog', { name: 'Salvar diagrama como template', exact: true });
  await editor.getByRole('textbox', { name: 'Nome do template' }).fill('API da minha equipe');
  await editor.getByRole('textbox', { name: 'Descrição do template' }).fill('Um exemplo reutilizável para o meu workspace.');
  await editor.getByRole('button', { name: 'Salvar template', exact: true }).click();
  await expect.poll(async () => JSON.parse((await readFile(page, 'library.json')) ?? '{}').templates?.length).toBe(1);
  await page.reload();
  await page.getByRole('button', { name: 'Modelos de diagramas', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Explorar modelos', exact: true }).click();
  const gallery = page.getByRole('dialog', { name: 'Modelos de diagramas' });
  await gallery.getByRole('button', { name: 'Meus modelos', exact: true }).click();
  await gallery.getByRole('button', { name: 'Ver modelo API da minha equipe', exact: true }).click();
  await gallery.getByRole('button', { name: 'Usar modelo', exact: true }).click();
  await expect(page.locator('[data-id="Kafka"]')).toBeVisible();
  await expect.poll(() => readFile(page, 'diagrams/api-da-minha-equipe.strukt.json')).not.toBeNull();
  await page.getByRole('button', { name: 'Modelos de diagramas', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Explorar modelos', exact: true }).click();
  await gallery.getByRole('button', { name: 'Excluir modelo API da minha equipe', exact: true }).click();
  await expect.poll(async () => JSON.parse((await readFile(page, 'library.json')) ?? '{"templates":[]}').templates?.length).toBe(0);
  expect(await readFile(page, 'diagrams/api-da-minha-equipe.strukt.json')).not.toBeNull();
  await gallery.getByRole('button', { name: 'Fechar', exact: true }).click();
  await page.getByRole('button', { name: 'Desfazer', exact: true }).click();
  await expect.poll(async () => JSON.parse((await readFile(page, 'library.json')) ?? '{}').templates?.length).toBe(1);
  await page.getByRole('button', { name: 'Menu do workspace' }).click();
  await page.getByRole('menuitem', { name: 'Meus projetos', exact: true }).click();
  await page.getByRole('button', { name: 'Novo workspace', exact: true }).click();
  const project = page.getByRole('dialog', { name: 'Novo workspace', exact: true });
  await project.getByRole('textbox', { name: 'Nome do workspace' }).fill('Outro projeto');
  await project.getByRole('button', { name: 'Criar workspace', exact: true }).click();
  await expect(project).toHaveCount(0);
  await page.getByRole('button', { name: 'Modelos de diagramas', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Explorar modelos', exact: true }).click();
  await expect(gallery.getByRole('button', { name: 'Meus modelos', exact: true })).toHaveCount(0);
  await expect(gallery.getByRole('button', { name: /^Ver modelo / })).toHaveCount(TEMPLATES.length);
  expect(await readFile(page, 'library.json')).toBeNull();
});
