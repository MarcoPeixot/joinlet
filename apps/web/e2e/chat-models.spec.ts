import { expect, test } from '@playwright/test';
import type { SettingsView } from '../src/settings/client';
import { axeFindings } from './support/axe';

for (const [width, theme] of [[1680, 'dark'], [390, 'dark'], [1680, 'light'], [390, 'light']] as const) {
  test(`chat models and quiet settings at ${width}px in ${theme}`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 960 });
    await page.addInitScript(theme => localStorage.setItem('strukt:theme', theme), theme);
    const ready = { configured: true, source: 'file' as const, hint: '…test' };
    const missing = { configured: false, source: null, hint: null };
    const view: SettingsView = { provider: 'opencodego', active: 'opencodego', providers: { opencodego: ready, openrouter: ready, anthropic: missing, opencode: missing, openai: missing }, models: { opencodego: { edit: 'glm-5.3-flash', generate: 'glm-5.3-flash', doc: 'glm-5.3-flash' }, opencode: { edit: 'big-pickle', generate: 'big-pickle', doc: 'big-pickle' }, openrouter: { edit: 'openrouter/auto', generate: 'openrouter/auto', doc: 'openrouter/auto' }, openai: { edit: '', generate: '', doc: '' } }, openai: { baseUrl: null } };
    let writes = 0;
    const requests: { selection?: { provider: string; model: string } }[] = [];
    await page.route('**/api/settings', route => { if (route.request().method() === 'POST') writes++; return route.fulfill({ json: view }); });
    await page.route('**/api/settings/opencode-go-models', route => route.fulfill({ json: { models: [{ id: 'glm-5.3-flash', name: 'GLM Flash', context: 0 }, { id: 'qwen3.8-flash', name: 'Qwen Flash', context: 0 }] } }));
    await page.route('**/api/settings/openrouter-models', route => route.fulfill({ json: { models: [{ id: 'test/reasoning-model', name: 'Reasoning model', context: 200000 }] } }));
    await page.route('**/api/ai/chat', route => { requests.push(route.request().postDataJSON()); return route.fulfill({ contentType: 'application/x-ndjson', body: '{"t":"Resposta com o modelo escolhido."}\n{"done":true}\n' }); });
    await page.goto('/app/');
    await expect(page.locator('.react-flow__node[data-id="Kafka"]')).toBeVisible();
    await expect(page.locator('.react-flow__attribution')).toHaveCount(0);
    const canvas = page.getByRole('main');
    const toolbar = page.locator('.sk-topbar-group');
    expect((await toolbar.boundingBox())!.y - (await canvas.boundingBox())!.y).toBeGreaterThanOrEqual(16);
    expect(parseFloat(await toolbar.evaluate(el => getComputedStyle(el).paddingTop))).toBeGreaterThanOrEqual(6);
    await page.getByRole('button', { name: 'Chat com a IA', exact: true }).click();
    const chat = page.getByRole('complementary', { name: 'Chat com a IA', exact: true });
    await chat.getByRole('button', { name: /Modelo e provider:/ }).click();
    const picker = page.getByRole('dialog', { name: 'Modelo e provider do chat', exact: true });
    await expect(picker.getByLabel('Provider do chat')).toHaveValue('opencodego');
    await picker.getByRole('button', { name: /Qwen Flash/ }).click();
    await expect(chat.getByRole('button', { name: /Modelo e provider: OpenCode Go · qwen3.8-flash/ })).toBeVisible();
    await chat.getByRole('textbox', { name: 'Mensagem para a IA' }).fill('Consulta com Go');
    await chat.getByRole('button', { name: 'Enviar', exact: true }).click();
    await expect(chat.getByText('Resposta com o modelo escolhido.', { exact: true })).toBeVisible();
    expect(requests[0]?.selection).toEqual({ provider: 'opencodego', model: 'qwen3.8-flash' });
    await chat.getByRole('button', { name: 'Nova conversa', exact: true }).click();
    await chat.getByRole('button', { name: /Modelo e provider:/ }).click();
    await picker.getByLabel('Provider do chat').selectOption('openrouter');
    await picker.getByLabel('Buscar modelo do chat').fill('reasoning');
    await picker.getByRole('button', { name: /Reasoning model/ }).click();
    await chat.getByRole('textbox', { name: 'Mensagem para a IA' }).fill('Consulta com Router');
    await chat.getByRole('button', { name: 'Enviar', exact: true }).click();
    await expect(chat.getByText('Resposta com o modelo escolhido.', { exact: true })).toBeVisible();
    expect(requests[1]?.selection).toEqual({ provider: 'openrouter', model: 'test/reasoning-model' });
    expect(writes).toBe(0);
    await page.reload();
    if (!await chat.isVisible()) await page.getByRole('button', { name: 'Chat com a IA', exact: true }).click();
    await expect(chat.getByRole('button', { name: /Modelo e provider: OpenRouter · test\/reasoning-model/ })).toBeVisible();
    await chat.getByRole('button', { name: 'Conversas anteriores', exact: true }).click();
    await page.getByRole('menuitemcheckbox', { name: /Consulta com Go/ }).click();
    await expect(chat.getByRole('button', { name: /Modelo e provider: OpenCode Go · qwen3.8-flash/ })).toBeVisible();
    await chat.getByRole('button', { name: /Modelo e provider:/ }).click();
    await expect(picker).toBeVisible();
    expect(await picker.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
    await page.screenshot({ path: info.outputPath('chat-model-picker.png'), animations: 'disabled' });
    expect(await axeFindings(page)).toEqual([]);
    await picker.getByLabel('Provider do chat').selectOption('anthropic');
    await picker.getByRole('button', { name: 'Configurar conexão', exact: true }).click();
    const settings = page.getByRole('dialog', { name: 'Configurações', exact: true });
    await expect(settings.getByRole('region', { name: 'Anthropic', exact: true })).toBeVisible();
    await settings.getByRole('button', { name: 'Configurar OpenCode Go', exact: true }).click();
    await expect(settings.getByRole('region', { name: 'OpenCode Go', exact: true })).toBeVisible();
    expect(await settings.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
    await page.screenshot({ path: info.outputPath('settings-providers.png'), animations: 'disabled' });
    expect(await axeFindings(page)).toEqual([]);
  });
}
